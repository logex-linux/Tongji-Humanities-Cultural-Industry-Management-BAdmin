  var fix = function (arr, field, valid) {
    arr.forEach(function (it) {
      var f = it[field];
      if (!f) return;
      for (var i = 0; i < f.length; i++) {
        var v = MAP[f[i]];
        if (v && valid[v]) f[i] = v;
      }
      // 去重，保持顺序
      var seen = {}, out = [];
      f.forEach(function (x) { if (valid[x] && !seen[x]) { seen[x] = 1; out.push(x); } });
      it[field] = out;
    });
  };

  window.ATLAS_FIX_DANGLING = function (industries, roles, models) {
    var rid = {}, mid = {};
    roles.forEach(function (r) { rid[r.id] = 1; });
    models.forEach(function (m) { mid[m.id] = 1; });
    fix(industries, 'models', mid);
    fix(industries, 'roles', rid);
  };
